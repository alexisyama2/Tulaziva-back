namespace Tulaziva.Domain.Entities;

public class Message
{
    public Guid Id { get; set; } = Guid.NewGuid();

    public Guid ConversationId { get; set; }
    public Conversation Conversation { get; set; } = null!;

    public Guid SenderId { get; set; }
    public User Sender { get; set; } = null!;

    /// <summary>The text. Null when the message is only files.</summary>
    public string? Body { get; set; }

    public DateTime CreatedAtUtc { get; set; } = DateTime.UtcNow;

    /// <summary>When the other participant read it. Null while unread.</summary>
    public DateTime? ReadAtUtc { get; set; }

    public List<MessageAttachment> Attachments { get; set; } = new();
}

public class MessageAttachment
{
    public Guid Id { get; set; } = Guid.NewGuid();

    public Guid MessageId { get; set; }
    public Message Message { get; set; } = null!;

    /// <summary>Path inside the storage, with "/" as separator. Generated by the server.</summary>
    public string StoragePath { get; set; } = string.Empty;

    /// <summary>The name the sender gave the file, cleaned of paths and control characters. Only used to name the download.</summary>
    public string FileName { get; set; } = string.Empty;

    /// <summary>Decided by the server from the extension that was checked against the content, never taken from the client.</summary>
    public string ContentType { get; set; } = string.Empty;

    public long SizeBytes { get; set; }

    public DateTime CreatedAtUtc { get; set; } = DateTime.UtcNow;
}
