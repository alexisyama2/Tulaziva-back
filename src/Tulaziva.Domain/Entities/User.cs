using Tulaziva.Domain.Enums;

namespace Tulaziva.Domain.Entities;

public class User
{
    public Guid Id { get; set; } = Guid.NewGuid();

    /// <summary>Always stored lower-cased, so the login lookup does not depend on the database collation.</summary>
    public string Email { get; set; } = string.Empty;

    public string PasswordHash { get; set; } = string.Empty;

    public string DisplayName { get; set; } = string.Empty;

    public UserRole Role { get; set; } = UserRole.User;

    /// <summary>Two-letter language code (es, en) used for the messages sent to this user.</summary>
    public string PreferredLanguage { get; set; } = "es";

    /// <summary>Where the user registered from. Null when the client did not send a location. Used later to search ads by distance.</summary>
    public double? RegistrationLatitude { get; set; }

    public double? RegistrationLongitude { get; set; }

    /// <summary>Path of the profile photo inside the storage ("/" as separator), generated by the server. Null when the user has none.</summary>
    public string? ProfilePhotoPath { get; set; }

    /// <summary>image/jpeg or image/png, decided by the server from the checked file.</summary>
    public string? ProfilePhotoContentType { get; set; }

    /// <summary>When the photo was last changed. It goes in the photo URL, so a new photo is not shown from an old cache.</summary>
    public DateTime? ProfilePhotoUpdatedAtUtc { get; set; }

    /// <summary>When the user proved the address is theirs (by following the link of the email). Null while unverified.</summary>
    public DateTime? EmailVerifiedAtUtc { get; set; }

    /// <summary>When the user accepted the terms of use and the privacy notice at sign-up. Null for accounts created before they were required.</summary>
    public DateTime? TermsAcceptedAtUtc { get; set; }

    /// <summary>Which version of the terms was accepted (see LegalRules.TermsVersion), to know who has to accept a newer one.</summary>
    public string? TermsVersion { get; set; }

    public bool IsActive { get; set; } = true;

    /// <summary>When the user deleted the account. The row stays, anonymized, because chats and reports point to it; null for a live account.</summary>
    public DateTime? DeletedAtUtc { get; set; }

    public DateTime CreatedAtUtc { get; set; } = DateTime.UtcNow;

    public DateTime? LastLoginAtUtc { get; set; }
}
