using Tulaziva.Domain.Entities;

namespace Tulaziva.Application.Ads;

public sealed record AdSearchCriteria(
    string? Text,
    int? CategoryId,
    decimal? MinPrice,
    decimal? MaxPrice,
    double? Latitude,
    double? Longitude,
    double? RadiusKm,
    int Page,
    int PageSize);

public sealed record AdSearchHit(Ad Ad, double? DistanceKm);

public interface IAdRepository
{
    /// <summary>The ad with its images and its owner, tracked so it can be changed and saved.</summary>
    Task<Ad?> GetByIdAsync(Guid id, CancellationToken cancellationToken);

    /// <summary>The ads of a user, whatever their status, newest first. Page is 1-based.</summary>
    Task<(IReadOnlyList<Ad> Items, int TotalCount)> GetByOwnerAsync(Guid ownerId, int page, int pageSize, CancellationToken cancellationToken);

    /// <summary>
    /// The active ads that have not expired and match the criteria. Newest first, or nearest first when the criteria
    /// have a location (ads without location go last).
    /// </summary>
    Task<(IReadOnlyList<AdSearchHit> Items, int TotalCount)> SearchAsync(AdSearchCriteria criteria, DateTime nowUtc, CancellationToken cancellationToken);

    Task AddAsync(Ad ad, CancellationToken cancellationToken);

    /// <summary>Removes the ad and its image rows. The files are removed by the caller.</summary>
    void Remove(Ad ad);

    /// <summary>
    /// Adds a new image to its ad. It must go through the repository and not through ad.Images.Add: the image already has its id,
    /// and an entity with an id that is found through a collection is taken as an existing row, not as a new one.
    /// </summary>
    void AddImage(AdImage image);

    void RemoveImage(AdImage image);

    Task SaveChangesAsync(CancellationToken cancellationToken);
}

public interface ICategoryRepository
{
    Task<IReadOnlyList<Category>> GetAllAsync(CancellationToken cancellationToken);

    Task<bool> ExistsAsync(int id, CancellationToken cancellationToken);
}

/// <summary>Where the uploaded files are kept. The paths it hands out are relative, generated by the storage, and use "/" as separator.</summary>
public interface IFileStorage
{
    Task<string> SaveAsync(string folder, Stream content, string extension, CancellationToken cancellationToken);

    /// <summary>The file, or null when it does not exist. The caller disposes the stream.</summary>
    Task<Stream?> OpenReadAsync(string path, CancellationToken cancellationToken);

    /// <summary>Removes the file. Does nothing when it does not exist.</summary>
    Task DeleteAsync(string path, CancellationToken cancellationToken);
}
